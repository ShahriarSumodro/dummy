import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:intl/intl.dart';
import '../models/meeting.dart';
import '../models/commitment.dart';
import '../services/database_service.dart';
import '../theme/app_haptics.dart';
import '../theme/design_tokens.dart';
import '../widgets/widgets.dart';
import 'meeting_form_screen.dart';

/// Screen displaying the meeting summary, decisions, action items, and raw notes.
class MeetingDetailScreen extends StatefulWidget {
  final int meetingId;

  const MeetingDetailScreen({super.key, required this.meetingId});

  @override
  State<MeetingDetailScreen> createState() => _MeetingDetailScreenState();
}

class _MeetingDetailScreenState extends State<MeetingDetailScreen> {
  final _db = DatabaseService();
  Meeting? _meeting;
  bool _loading = true;

  @override
  void initState() {
    super.initState();
    _loadMeeting();
  }

  Future<void> _loadMeeting() async {
    final meeting = await _db.getMeeting(widget.meetingId);
    if (mounted) {
      setState(() {
        _meeting = meeting;
        _loading = false;
      });
    }
  }

  Future<void> _convertActionItemToCommitment(String actionText) async {
    AppHaptics.success();
    final commitment = Commitment(
      title: actionText,
      description: 'Extracted from meeting: "${_meeting?.title}"',
      type: CommitmentType.task,
      dueDate: DateTime.now().add(const Duration(days: 3)),
    );

    await _db.insertCommitment(commitment);
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Created promise: "$actionText"'),
          backgroundColor: AppColors.success,
          behavior: SnackBarBehavior.floating,
          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(AppRadius.md)),
        ),
      );
    }
  }

  Future<void> _deleteMeeting() async {
    AppHaptics.warning();
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (_) => AlertDialog(
        title: const Text('Delete Meeting'),
        content: Text('Delete "${_meeting?.title}"?'),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Cancel'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(context, true),
            style: TextButton.styleFrom(foregroundColor: AppColors.error),
            child: const Text('Delete'),
          ),
        ],
      ),
    );

    if (confirmed == true && mounted) {
      AppHaptics.success();
      await _db.deleteMeeting(widget.meetingId);
      if (mounted) {
        Navigator.pop(context, true);
      }
    }
  }

  void _exportMeetingMinutes() {
    if (_meeting == null) return;
    AppHaptics.lightImpact();
    final m = _meeting!;
    final dateFormat = DateFormat('EEEE, MMM d, yyyy · h:mm a');
    final buffer = StringBuffer();
    buffer.writeln('# Meeting Minutes: ${m.title}');
    buffer.writeln('Date: ${dateFormat.format(m.meetingDate)}');
    if (m.location != null && m.location!.isNotEmpty) {
      buffer.writeln('Location: ${m.location}');
    }
    if (m.organizationName != null && m.organizationName!.isNotEmpty) {
      buffer.writeln('Organization: ${m.organizationName}');
    }
    buffer.writeln();

    if (m.summary != null && m.summary!.isNotEmpty) {
      buffer.writeln('## Executive Summary\n${m.summary}\n');
    }

    if (m.decisions.isNotEmpty) {
      buffer.writeln('## Key Decisions');
      for (final d in m.decisions) {
        buffer.writeln('- $d');
      }
      buffer.writeln();
    }

    if (m.actionItems.isNotEmpty) {
      buffer.writeln('## Action Items');
      for (final a in m.actionItems) {
        buffer.writeln('- [ ] $a');
      }
      buffer.writeln();
    }

    if (m.rawNotes != null && m.rawNotes!.isNotEmpty) {
      buffer.writeln('## Discussion Notes\n${m.rawNotes}\n');
    }

    buffer.writeln('---\nGenerated by Dummy.');

    Clipboard.setData(ClipboardData(text: buffer.toString()));
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: const Text('Meeting minutes copied to clipboard in markdown.'),
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(AppRadius.md)),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    if (_loading) {
      return Scaffold(
        backgroundColor: AppColors.background(context),
        appBar: AppBar(),
        body: ListView(
          padding: const EdgeInsets.all(AppSpacing.md),
          children: const [
            AppSkeleton(height: 120),
            SizedBox(height: AppSpacing.md),
            AppSkeleton(height: 160),
            SizedBox(height: AppSpacing.md),
            AppSkeleton(height: 140),
          ],
        ),
      );
    }

    if (_meeting == null) {
      return Scaffold(
        backgroundColor: AppColors.background(context),
        appBar: AppBar(),
        body: const Center(
          child: AppEmptyState(
            icon: Icons.meeting_room_outlined,
            title: 'Meeting not found',
            message: 'This meeting entry may have been removed.',
          ),
        ),
      );
    }

    final m = _meeting!;
    final dateFormat = DateFormat('EEEE, MMM d, yyyy · h:mm a');

    return Scaffold(
      backgroundColor: AppColors.background(context),
      appBar: AppBar(
        titleSpacing: 0,
        title: Text(m.title, style: const TextStyle(fontWeight: FontWeight.w700)),
        actions: [
          IconButton(
            icon: const Icon(Icons.share_outlined),
            tooltip: 'Copy Meeting Minutes',
            onPressed: _exportMeetingMinutes,
          ),
          IconButton(
            icon: const Icon(Icons.edit_outlined),
            tooltip: 'Edit Meeting',
            onPressed: () async {
              AppHaptics.lightImpact();
              final updated = await Navigator.push<Meeting>(
                context,
                MaterialPageRoute(builder: (_) => MeetingFormScreen(meeting: m)),
              );
              if (updated != null) {
                await _db.updateMeeting(updated);
                _loadMeeting();
              }
            },
          ),
          IconButton(
            icon: const Icon(Icons.delete_outline_rounded),
            tooltip: 'Delete Meeting',
            onPressed: _deleteMeeting,
          ),
          const SizedBox(width: AppSpacing.xs),
        ],
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(AppSpacing.md, AppSpacing.sm, AppSpacing.md, AppSpacing.xxl),
        children: [
          // Meta Details Card
          AppCard(
            padding: const EdgeInsets.all(AppSpacing.md),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    const Icon(Icons.calendar_today_rounded, size: 16, color: AppColors.primary),
                    const SizedBox(width: AppSpacing.xs),
                    Text(
                      dateFormat.format(m.meetingDate),
                      style: const TextStyle(fontWeight: FontWeight.w600, fontSize: 13),
                    ),
                  ],
                ),
                if (m.location != null && m.location!.isNotEmpty) ...[
                  const SizedBox(height: AppSpacing.xs),
                  Row(
                    children: [
                      Icon(Icons.location_on_outlined, size: 16, color: AppColors.muted(context)),
                      const SizedBox(width: AppSpacing.xs),
                      Text(m.location!, style: TextStyle(fontSize: 13, color: AppColors.muted(context))),
                    ],
                  ),
                ],
                if (m.organizationName != null && m.organizationName!.isNotEmpty) ...[
                  const SizedBox(height: AppSpacing.xs),
                  Row(
                    children: [
                      Icon(Icons.business_outlined, size: 16, color: AppColors.muted(context)),
                      const SizedBox(width: AppSpacing.xs),
                      Text(m.organizationName!, style: TextStyle(fontSize: 13, color: AppColors.muted(context))),
                    ],
                  ),
                ],
              ],
            ),
          ),
          const SizedBox(height: AppSpacing.md),

          // Executive Summary
          if (m.summary != null && m.summary!.isNotEmpty) ...[
            AppSectionHeader(title: 'Executive Summary'),
            const SizedBox(height: AppSpacing.xs),
            AppCard(
              padding: const EdgeInsets.all(AppSpacing.md),
              child: Text(
                m.summary!,
                style: const TextStyle(fontSize: 14, height: 1.55),
              ),
            ),
            const SizedBox(height: AppSpacing.lg),
          ],

          // Key Decisions
          if (m.decisions.isNotEmpty) ...[
            AppSectionHeader(
              title: 'Key Decisions',
              count: m.decisions.length,
            ),
            const SizedBox(height: AppSpacing.xs),
            AppCard(
              padding: const EdgeInsets.all(AppSpacing.md),
              child: Column(
                children: m.decisions.map((d) {
                  return Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: Row(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        const Icon(Icons.check_circle_outline_rounded, size: 16, color: AppColors.success),
                        const SizedBox(width: AppSpacing.sm),
                        Expanded(
                          child: Text(d, style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w500)),
                        ),
                      ],
                    ),
                  );
                }).toList(),
              ),
            ),
            const SizedBox(height: AppSpacing.lg),
          ],

          // Action Items
          if (m.actionItems.isNotEmpty) ...[
            AppSectionHeader(
              title: 'Action Items',
              count: m.actionItems.length,
            ),
            const SizedBox(height: AppSpacing.xs),
            ...m.actionItems.map((action) => Padding(
                  padding: const EdgeInsets.only(bottom: AppSpacing.xs),
                  child: AppListRow(
                    leading: const Icon(Icons.task_alt_rounded, size: 18, color: AppColors.primary),
                    title: action,
                    trailing: AppButton(
                      label: '+ Promise',
                      size: AppButtonSize.sm,
                      variant: AppButtonVariant.tonal,
                      onPressed: () => _convertActionItemToCommitment(action),
                    ),
                  ),
                )),
            const SizedBox(height: AppSpacing.lg),
          ],

          // Discussion Notes
          if (m.rawNotes != null && m.rawNotes!.isNotEmpty) ...[
            AppSectionHeader(title: 'Discussion Notes'),
            const SizedBox(height: AppSpacing.xs),
            AppCard(
              padding: const EdgeInsets.all(AppSpacing.md),
              child: Text(
                m.rawNotes!,
                style: TextStyle(
                  fontSize: 13,
                  height: 1.55,
                  color: AppColors.foreground(context),
                ),
              ),
            ),
            const SizedBox(height: AppSpacing.lg),
          ],
        ],
      ),
    );
  }
}
