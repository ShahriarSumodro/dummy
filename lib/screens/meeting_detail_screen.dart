import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:intl/intl.dart';
import '../models/meeting.dart';
import '../models/commitment.dart';
import '../services/database_service.dart';
import 'meeting_form_screen.dart';

/// Screen displaying the meeting summary, decisions, action items, and raw notes.
class MeetingDetailScreen extends StatefulWidget {
  final int meetingId;

  const MeetingDetailScreen({super.key, required this.meetingId});

  @override
  State<MeetingDetailScreen> createState() => _MeetingDetailScreenState();
}

class _MeetingDetailScreenState extends State<MeetingDetailScreen> {
  final _db = DatabaseService();
  Meeting? _meeting;
  bool _loading = true;

  @override
  void initState() {
    super.initState();
    _loadMeeting();
  }

  Future<void> _loadMeeting() async {
    final meeting = await _db.getMeeting(widget.meetingId);
    if (mounted) {
      setState(() {
        _meeting = meeting;
        _loading = false;
      });
    }
  }

  Future<void> _convertActionItemToCommitment(String actionText) async {
    final commitment = Commitment(
      title: actionText,
      description: 'Extracted from meeting: "${_meeting?.title}"',
      type: CommitmentType.task,
      dueDate: DateTime.now().add(const Duration(days: 3)),
    );

    await _db.insertCommitment(commitment);
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Created commitment: "$actionText"'),
          backgroundColor: Colors.green,
        ),
      );
    }
  }

  Future<void> _deleteMeeting() async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (_) => AlertDialog(
        title: const Text('Delete Meeting'),
        content: Text('Delete "${_meeting?.title}"?'),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Cancel'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(context, true),
            style: TextButton.styleFrom(foregroundColor: Colors.red),
            child: const Text('Delete'),
          ),
        ],
      ),
    );

    if (confirmed == true && mounted) {
      await _db.deleteMeeting(widget.meetingId);
      if (mounted) {
        Navigator.pop(context, true);
      }
    }
  }

  void _exportMeetingMinutes() {
    if (_meeting == null) return;
    final m = _meeting!;
    final dateFormat = DateFormat('EEEE, MMM d, yyyy · h:mm a');
    final buffer = StringBuffer();
    buffer.writeln('# Meeting Minutes: ${m.title}');
    buffer.writeln('Date: ${dateFormat.format(m.meetingDate)}');
    if (m.location != null && m.location!.isNotEmpty) {
      buffer.writeln('Location: ${m.location}');
    }
    if (m.organizationName != null && m.organizationName!.isNotEmpty) {
      buffer.writeln('Organization: ${m.organizationName}');
    }
    buffer.writeln();

    if (m.summary != null && m.summary!.isNotEmpty) {
      buffer.writeln('## Executive Summary\n${m.summary}\n');
    }

    if (m.decisions.isNotEmpty) {
      buffer.writeln('## Key Decisions');
      for (final d in m.decisions) {
        buffer.writeln('- $d');
      }
      buffer.writeln();
    }

    if (m.actionItems.isNotEmpty) {
      buffer.writeln('## Action Items');
      for (final a in m.actionItems) {
        buffer.writeln('- [ ] $a');
      }
      buffer.writeln();
    }

    if (m.rawNotes != null && m.rawNotes!.isNotEmpty) {
      buffer.writeln('## Discussion Notes\n${m.rawNotes}\n');
    }

    buffer.writeln('---\nGenerated by RemembrAI');

    Clipboard.setData(ClipboardData(text: buffer.toString()));
    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text('Meeting minutes copied to clipboard in markdown.'),
        behavior: SnackBarBehavior.floating,
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    if (_loading) {
      return Scaffold(
        appBar: AppBar(),
        body: const Center(child: CircularProgressIndicator()),
      );
    }

    if (_meeting == null) {
      return Scaffold(
        appBar: AppBar(),
        body: const Center(child: Text('Meeting not found')),
      );
    }

    final m = _meeting!;
    final theme = Theme.of(context);
    final dateFormat = DateFormat('EEEE, MMM d, yyyy · h:mm a');

    return Scaffold(
      appBar: AppBar(
        title: Text(m.title),
        actions: [
          IconButton(
            icon: const Icon(Icons.share_outlined),
            tooltip: 'Copy Meeting Minutes',
            onPressed: _exportMeetingMinutes,
          ),
          IconButton(
            icon: const Icon(Icons.edit_outlined),
            onPressed: () async {
              final updated = await Navigator.push<Meeting>(
                context,
                MaterialPageRoute(
                  builder: (_) => MeetingFormScreen(meeting: m),
                ),
              );
              if (updated != null) {
                await _db.updateMeeting(updated);
                _loadMeeting();
              }
            },
          ),
          IconButton(
            icon: const Icon(Icons.delete_outline),
            onPressed: _deleteMeeting,
          ),
        ],
      ),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          // Meta details card
          Card(
            elevation: 0,
            color: theme.colorScheme.surfaceContainerHighest.withValues(alpha: 0.4),
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      const Icon(Icons.calendar_today, size: 18),
                      const SizedBox(width: 8),
                      Text(dateFormat.format(m.meetingDate)),
                    ],
                  ),
                  if (m.location != null) ...[
                    const SizedBox(height: 8),
                    Row(
                      children: [
                        const Icon(Icons.location_on_outlined, size: 18),
                        const SizedBox(width: 8),
                        Text(m.location!),
                      ],
                    ),
                  ],
                  if (m.organizationName != null) ...[
                    const SizedBox(height: 8),
                    Row(
                      children: [
                        const Icon(Icons.business_outlined, size: 18),
                        const SizedBox(width: 8),
                        Text(m.organizationName!),
                      ],
                    ),
                  ],
                ],
              ),
            ),
          ),
          const SizedBox(height: 20),

          // Summary Section
          if (m.summary != null && m.summary!.isNotEmpty) ...[
            Text(
              'Executive Summary',
              style: theme.textTheme.titleMedium?.copyWith(
                fontWeight: FontWeight.bold,
              ),
            ),
            const SizedBox(height: 8),
            Card(
              child: Padding(
                padding: const EdgeInsets.all(14),
                child: Text(
                  m.summary!,
                  style: const TextStyle(height: 1.4, fontSize: 14),
                ),
              ),
            ),
            const SizedBox(height: 20),
          ],

          // Decisions Section
          if (m.decisions.isNotEmpty) ...[
            Text(
              'Decisions Made (${m.decisions.length})',
              style: theme.textTheme.titleMedium?.copyWith(
                fontWeight: FontWeight.bold,
              ),
            ),
            const SizedBox(height: 8),
            ...m.decisions.map((d) => Card(
                  margin: const EdgeInsets.only(bottom: 8),
                  child: ListTile(
                    leading: const Icon(Icons.check_circle, color: Colors.green),
                    title: Text(d),
                  ),
                )),
            const SizedBox(height: 20),
          ],

          // Action Items Section
          if (m.actionItems.isNotEmpty) ...[
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Text(
                  'Action Items (${m.actionItems.length})',
                  style: theme.textTheme.titleMedium?.copyWith(
                    fontWeight: FontWeight.bold,
                  ),
                ),
                Text(
                  'Tap + to track',
                  style: theme.textTheme.labelSmall?.copyWith(
                    color: theme.colorScheme.outline,
                  ),
                ),
              ],
            ),
            const SizedBox(height: 8),
            ...m.actionItems.map((a) => Card(
                  margin: const EdgeInsets.only(bottom: 8),
                  child: ListTile(
                    leading: const Icon(Icons.task_alt, color: Colors.blue),
                    title: Text(a),
                    trailing: IconButton(
                      icon: const Icon(Icons.add_task),
                      tooltip: 'Convert to tracked commitment',
                      onPressed: () => _convertActionItemToCommitment(a),
                    ),
                  ),
                )),
            const SizedBox(height: 20),
          ],

          // Raw Notes Section
          if (m.rawNotes != null && m.rawNotes!.isNotEmpty) ...[
            Text(
              'Raw Meeting Notes',
              style: theme.textTheme.titleMedium?.copyWith(
                fontWeight: FontWeight.bold,
              ),
            ),
            const SizedBox(height: 8),
            Card(
              elevation: 0,
              child: Padding(
                padding: const EdgeInsets.all(14),
                child: SelectableText(
                  m.rawNotes!,
                  style: const TextStyle(fontSize: 13, height: 1.4),
                ),
              ),
            ),
            const SizedBox(height: 40),
          ],
        ],
      ),
    );
  }
}
